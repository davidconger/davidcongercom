#!/usr/bin/env node
'use strict';

/*
 * tidy-frontpage.js — removes the last of the FrontPage / Expression Web
 * artifacts from the page tree.
 *
 * Passes (opt in with flags, or use --all):
 *
 *   --targets         target="_top" is a frameset-era instruction meaning
 *                     "escape any surrounding frameset". This site has no
 *                     framesets, so on every one of the 11,443 pages carrying
 *                     it the attribute does nothing at all. External links get
 *                     target="_blank" rel="noopener" instead, so the social
 *                     icons open alongside the site rather than replacing it.
 *                     mailto: links just lose the attribute — handing a mail
 *                     link to a new tab leaves an empty tab behind.
 *
 *   --dead-classes    class="auto-style1|2|3" and class="style3|style4" are
 *                     Expression Web autogenerated names that are defined in
 *                     no stylesheet. style1 and style2 are deliberately kept:
 *                     they are live on the flat gallery pages.
 *
 *   --presentational  align="..." on block elements and language="JavaScript"
 *                     on <script>. Both obsolete in HTML5; the layout already
 *                     comes from CSS.
 *
 * Usage:
 *   node tools/tidy-frontpage.js --all --dry
 *   node tools/tidy-frontpage.js --targets
 *   node tools/tidy-frontpage.js --all --sample 5
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SKIP = new Set(['.git', 'node_modules', 'you_old', 'davidconger_backup', 'tools']);

/* Classes Expression Web invented and never defined. style1/style2 are live. */
const DEAD_CLASSES = new Set(['auto-style1', 'auto-style2', 'auto-style3', 'style3', 'style4']);

/* ------------------------------------------------------------------ */
/* pass: link targets                                                  */
/* ------------------------------------------------------------------ */

function fixTargets(html) {
  return html.replace(/<a\b[^>]*>/gi, (tag) => {
    if (!/\starget\s*=\s*["']_top["']/i.test(tag)) return tag;

    const href = (tag.match(/\shref\s*=\s*["']([^"']*)["']/i) || [])[1] || '';
    const external = /^https?:\/\//i.test(href);

    if (!external) {
      /* Same-site or mailto: the attribute is simply noise. */
      return tag.replace(/\s+target\s*=\s*["']_top["']/i, '');
    }

    let out = tag.replace(/\starget\s*=\s*["']_top["']/i, ' target="_blank"');

    const rel = out.match(/\srel\s*=\s*["']([^"']*)["']/i);
    if (rel) {
      const parts = rel[1].split(/\s+/).filter(Boolean);
      if (!parts.some((p) => p.toLowerCase() === 'noopener')) {
        parts.push('noopener');
        out = out.replace(/\srel\s*=\s*["'][^"']*["']/i, ` rel="${parts.join(' ')}"`);
      }
    } else {
      out = out.replace(/\starget="_blank"/, ' target="_blank" rel="noopener"');
    }
    return out;
  });
}

/* ------------------------------------------------------------------ */
/* pass: classes that reference nothing                                */
/* ------------------------------------------------------------------ */

function fixDeadClasses(html) {
  /*
   * A <span> whose only reason to exist was one of those class names is left
   * behind as a bare <span>, which is inert but still litter. Unwrap it, but
   * only when it holds plain text: anything with a tag inside could be nested
   * and is not safe to unwrap with a regex.
   */
  const out = html.replace(
    /<span\s+class\s*=\s*"([^"]*)"\s*>([^<]*)<\/span>/gi,
    (whole, value, text) => {
      const names = value.split(/\s+/).filter(Boolean);
      return names.length && names.every((c) => DEAD_CLASSES.has(c.toLowerCase())) ? text : whole;
    }
  );

  return out.replace(/\sclass\s*=\s*"([^"]*)"/gi, (attr, value) => {
    const names = value.split(/\s+/).filter(Boolean);
    const kept = names.filter((c) => !DEAD_CLASSES.has(c.toLowerCase()));
    if (kept.length === names.length) return attr;
    return kept.length ? ` class="${kept.join(' ')}"` : '';
  });
}

/* ------------------------------------------------------------------ */
/* pass: presentational attributes                                     */
/* ------------------------------------------------------------------ */

function fixPresentational(html) {
  let out = html.replace(
    /<(td|th|tr|table|div|p|h[1-6]|img|caption|col|colgroup|thead|tbody|tfoot)\b[^>]*>/gi,
    (tag) => tag.replace(/\s+align\s*=\s*["']?(?:left|right|center|middle|justify)["']?/gi, '')
  );
  out = out.replace(/<script\b[^>]*>/gi, (tag) =>
    tag.replace(/\s+language\s*=\s*["']?javascript["']?/gi, '')
  );
  return out;
}

/* ------------------------------------------------------------------ */

const PASSES = [
  ['targets', fixTargets],
  ['dead-classes', fixDeadClasses],
  ['presentational', fixPresentational],
];

function walk(dir, out) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP.has(entry.name.toLowerCase())) walk(full, out);
      continue;
    }
    if (/\.(htm|html)$/i.test(entry.name)) out.push(full);
  }
  return out;
}

function main() {
  const argv = process.argv.slice(2);
  const dry = argv.includes('--dry');
  const all = argv.includes('--all');
  const sampleAt = argv.indexOf('--sample');
  const sample = sampleAt > -1 ? Number(argv[sampleAt + 1]) : 0;

  const active = PASSES.filter(([name]) => all || argv.includes('--' + name));
  if (!active.length) {
    console.error('Nothing to do. Pass --all, or one of: ' + PASSES.map((p) => '--' + p[0]).join(', '));
    process.exit(1);
  }

  console.log('passes: ' + active.map((p) => p[0]).join(', ') + (dry ? '  (dry run)' : ''));

  const files = walk(ROOT, []);
  const tally = Object.fromEntries(active.map(([name]) => [name, 0]));
  let changed = 0;
  const shown = [];

  for (const file of files) {
    let before;
    try {
      before = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    let after = before;
    for (const [name, fn] of active) {
      const step = fn(after);
      if (step !== after) tally[name]++;
      after = step;
    }
    if (after === before) continue;
    changed++;
    if (shown.length < sample) shown.push([file, before, after]);
    if (!dry) fs.writeFileSync(file, after);
  }

  console.log(`scanned ${files.length} pages, changed ${changed}`);
  for (const [name] of active) console.log(`  ${name.padEnd(16)} ${tally[name]} pages`);

  for (const [file, before, after] of shown) {
    console.log('\n--- ' + path.relative(ROOT, file) + ' ---');
    const b = before.split(/\r?\n/);
    const a = after.split(/\r?\n/);
    let printed = 0;
    for (let i = 0; i < Math.max(b.length, a.length) && printed < 6; i++) {
      if (b[i] !== a[i]) {
        console.log('  - ' + (b[i] || '').trim());
        console.log('  + ' + (a[i] || '').trim());
        printed++;
      }
    }
  }
}

if (require.main === module) main();

module.exports = { fixTargets, fixDeadClasses, fixPresentational };
