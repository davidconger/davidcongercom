/**
 * Inventories the /you/ pages the lightbox has made redundant, and proves every
 * one of them can be redirected somewhere real before any of them is deleted.
 *
 * Three shapes are retiring:
 *
 *   you/<year>/<event>/gallery/<stem>-NN.htm    one photograph, newer layout
 *   you/<year>/<event>/page-N/<stem>-NN.htm     one photograph, older layout
 *   you/<year>/<event>/page-N.htm               a page of thumbnails
 *
 * The first two become /you/<year>/<event>/?p=NN, which the lightbox turns into
 * #p-NN on arrival. The third becomes the event page itself. The list is
 * written to disk so the redirects can still be checked after the files
 * themselves are gone.
 *
 *   node tools/inventory-you-pages.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const YOU = path.join(ROOT, 'you');
const OUT = path.join(ROOT, 'tools', 'you-retired-urls.txt');

const rel = (p) => path.relative(ROOT, p).replace(/\\/g, '/');

const entries = [];
const problems = [];
let events = 0;

for (const year of fs.readdirSync(YOU, { withFileTypes: true })) {
	if (!year.isDirectory() || year.name === '!template') continue;
	for (const ev of fs.readdirSync(path.join(YOU, year.name), { withFileTypes: true })) {
		if (!ev.isDirectory()) continue;
		const dir = path.join(YOU, year.name, ev.name);
		if (rel(dir) === 'you/2023/Old') continue;
		const index = path.join(dir, 'index.htm');
		if (!fs.existsSync(index)) continue;
		events++;

		const target = '/' + rel(dir) + '/';
		const photoIds = new Set(
			[...fs.readFileSync(index, 'utf8').matchAll(/<li id="([^"]*)"/g)].map((m) => m[1])
		);

		for (const child of fs.readdirSync(dir, { withFileTypes: true })) {
			if (child.isFile() && /^page-\d+\.htm$/i.test(child.name)) {
				entries.push({ url: '/' + rel(path.join(dir, child.name)), expect: target, kind: 'page' });
				continue;
			}
			if (!child.isDirectory()) continue;
			if (!/^(gallery|page-\d+)$/i.test(child.name)) continue;

			for (const f of fs.readdirSync(path.join(dir, child.name))) {
				if (!/\.html?$/i.test(f)) continue;
				const url = '/' + rel(path.join(dir, child.name, f));
				const num = f.match(/-(\d+)\.html?$/i);
				if (!num) {
					entries.push({ url, expect: target, kind: 'photo-unnumbered' });
					continue;
				}
				const id = 'p-' + num[1];
				if (!photoIds.has(id)) problems.push(url + ' -> ' + id + ' is not on ' + target);
				entries.push({ url, expect: target + '?p=' + num[1], kind: 'photo', id });
			}
		}
	}
}

const byKind = entries.reduce((acc, e) => { acc[e.kind] = (acc[e.kind] || 0) + 1; return acc; }, {});
console.log('events: ' + events);
for (const k of Object.keys(byKind).sort()) console.log('  ' + k + ': ' + byKind[k]);
console.log('total retiring URLs: ' + entries.length);
console.log('photo numbers with no matching thumbnail: ' + problems.length);
for (const p of problems.slice(0, 20)) console.log('    ' + p);

// Only the URLs are recorded. What each one should redirect to is exactly what
// the rewrite rules compute, so storing that too would only be checking the
// rules against themselves; tools/rewrite-sim.js instead proves the rules land
// on a page that exists and on a photograph that is really on it.
const list = entries.map((e) => e.url).sort();
fs.writeFileSync(OUT, '# URLs retired when the lightbox replaced the per-photo pages.\n'
	+ '# Generated by tools/inventory-you-pages.js while those pages still existed.\n'
	+ '# tools/rewrite-sim.js replays them against web.config.\n'
	+ list.join('\n') + '\n');
console.log('wrote ' + rel(OUT));
