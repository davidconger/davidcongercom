var totalImages = 10;

var currentImageId = -1;
var imageIds = new Array(totalImages);

var keepRotating = false;

function RotateImage()
{
	if (currentImageId >= 0)
	{
		DeselectCircle(currentImageId)
	}
	
	currentImageId ++;
	if (currentImageId >= totalImages )
	{
		currentImageId = 0;
	}

	LoadImage(imageIds[currentImageId])

	SelectCircle(currentImageId)	
    	
    if (keepRotating)// && totalRotations < 15)
    {
	    window.setTimeout("RotateImage()",4000)
	}
}

function SelectCircle(id)
{
    document.getElementById("circle" + id).className = "circle circleSelected";
}

function DeselectCircle(id)
{
    document.getElementById("circle" + id).className = "circle";
}


function LoadImage(imageId)
{
	var splitString = imageArray[imageId].split(';');
	
    document.getElementById("focusImage").src = splitString[0] + splitString[1];//'url(' + splitString[0] + ')';
    document.getElementById("focusArtist").innerHTML = splitString[3];
    document.getElementById("focusVenue").innerHTML = ' at ' + splitString[4]; 
    document.getElementById("focusDate").innerHTML = splitString[2]; 
//  document.getElementById("focusBox").style.width = splitString[5] + 'px'; 
//  document.getElementById("focusBox").style.marginLeft = (640 - splitString[5] - 10) + 'px'; 
    
    document.getElementById("focusContainer").style.visibility = "visible";
}

function SkipToImage(circle)
{
	var skipToImageId = circle.id.substring(6);
	DeselectCircle(currentImageId);

	LoadImage(imageIds[skipToImageId])
	SelectCircle(skipToImageId)
	
	currentImageId = skipToImageId
}

function Start()
{
	PopulateImageIds();
	
	window.setTimeout("RotateImage()",1)
	keepRotating = true;
}

